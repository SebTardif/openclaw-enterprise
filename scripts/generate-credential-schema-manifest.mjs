import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { snapshotCanonicalJsonV1 } from "../packages/occ/src/credential-broker-v1/schema-json.ts";

const arguments_ = process.argv.slice(2);
if (arguments_.length > 1 || (arguments_.length === 1 && arguments_[0] !== "--check")) {
  throw new Error("Usage: node scripts/generate-credential-schema-manifest.mjs [--check]");
}

const root = new URL("../", import.meta.url);
const output = new URL("packages/occ/src/credential-broker-v1/schema-primitive-manifest.ts", root);
const hash = (value) => createHash("sha256").update(value).digest("hex");
const paths = [
  "packages/occ/src/credential-broker-v1/schema-admission.ts",
  "packages/occ/src/credential-broker-v1/schema-json.ts",
  "packages/occ/src/credential-broker-v1/schema-primitives.ts",
  "packages/occ/src/credential-gateway-v1/schema.ts",
];
const files = await Promise.all(
  paths.map(async (path) => ({ path, sha256: hash(await readFile(new URL(path, root))) })),
);
const { dependencies } = JSON.parse(
  await readFile(new URL("packages/occ/package.json", root), "utf8"),
);
const entries = [
  ["schema-interpreter", "oce-closed-schema-interpreter"],
  ["canonicalization", "oce-json-canonical"],
].map(([kind, name]) => {
  const entry = { kind, name, version: 1, files, dependencies: { ajv: dependencies.ajv } };
  const { canonicalJson } = snapshotCanonicalJsonV1(entry, { maxBytes: 65536, maxDepth: 8 });
  return { ...entry, digest: "sha256:" + hash("oce-core-schema-primitive-v1\0" + canonicalJson) };
});
const filepath = fileURLToPath(output);
const content = await format(
  "// Generated by scripts/generate-credential-schema-manifest.mjs; excludes this manifest.\n" +
    "export const CORE_SCHEMA_PRIMITIVE_MANIFEST_V1 = " +
    JSON.stringify(entries) +
    " as const;\n",
  { ...(await resolveConfig(filepath)), filepath },
);
if (arguments_[0] === "--check") {
  if ((await readFile(output, "utf8")) !== content) {
    throw new Error(
      "Schema primitive manifest is out of date; run node scripts/generate-credential-schema-manifest.mjs.",
    );
  }
  console.log("Schema primitive manifest is current.");
} else {
  await writeFile(output, content);
  console.log("Generated schema primitive manifest.");
}
